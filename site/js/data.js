// Прямоугольный блок с выступающими торцами (E — ширина торца, N — глубина западания середины)
function notched(x, y, w, h, dir, E = 9, N = 1.1) {
  const X0 = x, Y0 = y, X1 = x + w, Y1 = y + h;
  if (dir === 'h') return [[X0, Y0], [X0 + E, Y0], [X0 + E, Y0 + N], [X1 - E, Y0 + N], [X1 - E, Y0], [X1, Y0], [X1, Y1], [X1 - E, Y1], [X1 - E, Y1 - N], [X0 + E, Y1 - N], [X0 + E, Y1], [X0, Y1]];
  return [[X0, Y0], [X1, Y0], [X1, Y0 + E], [X1 - N, Y0 + E], [X1 - N, Y1 - E], [X1, Y1 - E], [X1, Y1], [X0, Y1], [X0, Y1 - E], [X0 + N, Y1 - E], [X0 + N, Y0 + E], [X0, Y0 + E]];
}
const rect = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];
// Линия [a, b]: точка на расстоянии t вдоль неё и со сдвигом off влево (по нормали)
function along([a, b], t, off = 0) {
  const L = Math.hypot(b[0] - a[0], b[1] - a[1]), dx = (b[0] - a[0]) / L, dy = (b[1] - a[1]) / L;
  return [a[0] + dx * t - dy * off, a[1] + dy * t + dx * off];
}
// Полоса вдоль линии между сдвигами o0 и o1
function strip(line, o0, o1) {
  const [a, b] = line, L = Math.hypot(b[0] - a[0], b[1] - a[1]);
  return [along(line, 0, o0), along(line, L, o0), along(line, L, o1), along(line, 0, o1)];
}
function stripTrees(line, off, step, z = 0) {
  const [a, b] = line, L = Math.hypot(b[0] - a[0], b[1] - a[1]), n = Math.round(L / step);
  return Array.from({ length: n + 1 }, (_, i) => [...along(line, L * i / n, off), z]);
}
function treeRow(x0, y0, x1, y1, step, z = 0) {
  const len = Math.hypot(x1 - x0, y1 - y0), n = Math.max(1, Math.round(len / step));
  return Array.from({ length: n + 1 }, (_, i) => [x0 + (x1 - x0) * i / n, y0 + (y1 - y0) * i / n, z]);
}

